// npm run photos:inventory -- writes docs/IMAGE_INVENTORY.md and docs/IMAGE_SLOTS.md.
//
// IMAGE_INVENTORY.md lists every image file in public/photos (name, size, orientation, weight) and
// the slot and pages it is used for. IMAGE_SLOTS.md has the page-to-slot mapping, the slots and,
// under "STILL NEEDED", which pictures are missing (with their exact file names). Nothing is
// generated: a slot without a photo shows a plain themed gradient.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  HOME_PHOTOS,
  MEERA_DEFAULT,
  MEERA_FOLDER,
  MEERA_POSES,
  PHOTO_SLOTS,
  SLOT_SHOWS,
  isTransparentSlot,
  pickPhoto,
} from '../vite-plugins/photo-slots.js';
import { imageSize } from './image-size.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'public', 'photos');
const docs = path.resolve(root, '..', 'docs');
const ls = (d, prefix = '') => {
  try {
    return fs.readdirSync(d).map((n) => `${prefix}${n}`);
  } catch {
    return [];
  }
};
const files = [...ls(dir), ...ls(path.join(dir, MEERA_FOLDER), `${MEERA_FOLDER}/`)];
const images = files.filter((f) => /\.(webp|jpe?g|png)$/i.test(f)).sort();
const kb = (b) => `${Math.round(b / 1024)} KB`;
const orientation = (w, h) =>
  Math.abs(w / h - 1) < 0.05 ? 'square' : w > h ? 'landscape' : 'portrait';

/** What the file can say about transparency without decoding pixels (PNG header, WebP flags). */
function transparency(file) {
  const b = fs.readFileSync(file);
  if (b.length > 29 && b.readUInt32BE(0) === 0x89504e47) {
    const colorType = b[25];
    if (colorType === 4 || colorType === 6) return 'alpha channel (check the corners)';
    return b.includes(Buffer.from('tRNS')) ? 'palette transparency' : 'no: opaque background';
  }
  if (b.toString('ascii', 8, 12) === 'WEBP' && b.toString('ascii', 12, 16) === 'VP8X') {
    return b[20] & 0x10 ? 'alpha channel' : 'no: opaque background';
  }
  return 'no: opaque background';
}

const USED = {
  'shop-background':
    'Alankar reception photo (the one with the ALANKAR sign): home section 1; the background of EVERY page that is not a division page (all dashboards, bookings list, Zen Chat, wallet, packages, gift cards, shop, orders, invoices, profile, receptionist, stylist and admin pages, login, register, For Zenotians); the booking page while "All" is chosen; the profile page (only this photo).',
  'salon-background': 'Home section 2; the /salon pages; the booking page while Salon is chosen.',
  'spa-background': 'Home section 3; the /spa pages; the booking page while Spa is chosen.',
  'parlor-background':
    'Home section 4; the /beauty-parlor pages; the booking page while Parlor is chosen.',
  'salon-hero': 'Framed header picture: Salon division page and the booking page (Salon).',
  'spa-hero': 'Framed header picture: Spa division page and the booking page (Spa).',
  'parlor-hero': 'Framed header picture: Parlor division page and the booking page (Parlor).',
};

let inv = `# Image inventory\n\nGenerated by \`npm run photos:inventory\`. Only the owner's real photos are used; nothing is drawn or generated. PNG, JPG, JPEG and WebP are accepted; \`npm run photos:optimize\` turns each into WebP + JPG at about 1920 px and a 960 px copy (\`<name>-960.webp/.jpg\`) and writes the low-quality placeholders (\`placeholders.json\`). Originals are kept in \`frontend/photos-originals/\` (git-ignored); the optimized files in \`frontend/public/photos/\` ARE committed.\n\n`;
inv += `## The four main pictures\n\n| Picture | Expected file | Found | Size | Orientation | Weight | 960 px copy |\n|---|---|---|---|---|---|---|\n`;
for (const slot of HOME_PHOTOS) {
  const file = pickPhoto(slot, files);
  const size = file ? imageSize(path.join(dir, file)) : null;
  const small = files.some((f) => f.toLowerCase().startsWith(`${slot}-960.`));
  const label = { 'shop-background': 'Alankar reception' }[slot] ?? slot.replace('-background', '');
  inv += file
    ? `| ${label} | ${slot}.(webp/jpg/jpeg/png) | ${file} | ${size ? `${size.width}x${size.height}` : '?'} | ${size ? orientation(size.width, size.height) : '?'} | ${kb(fs.statSync(path.join(dir, file)).size)} | ${small ? 'yes' : 'no'} |\n`
    : `| ${label} | ${slot}.(webp/jpg/jpeg/png) | **MISSING** | | | | |\n`;
}
const meeraNames = [MEERA_DEFAULT, ...MEERA_POSES.map((pose) => `meera-${pose}`)];
inv += `\n## Meera pictures (frontend/public/photos/meera)\n\nEach PNG is converted to WebP at 820x1024 (4:5, about 1024 px tall) and a 410x512 copy (\`<name>-512.webp\`), with a tiny blurred preview in \`placeholders.json\`. Originals are kept in \`frontend/photos-originals/meera/\` (git-ignored) and the PNGs in \`public/photos/meera/\` are left in place. A picture with a transparent background is shown as a cut-out; one without is shown in the soft framed style. Any pose without its own file shows \`meera\`.\n\n| Name | Original | Size | Weight | Transparent background | Shown as | WebP 1024 / 512 tall |\n|---|---|---|---|---|---|---|\n`;
const missingMeera = [];
for (const name of meeraNames) {
  const png = files.find((f) => f.toLowerCase() === `${MEERA_FOLDER}/${name}.png`);
  if (!png) {
    missingMeera.push(`${name}.png`);
    inv += `| ${name} | **MISSING** (expected \`${name}.png\`) | | | | | |\n`;
    continue;
  }
  const full = path.join(dir, png);
  const size = imageSize(full);
  const clear = transparency(full);
  const big = files.find((f) => f.toLowerCase() === `${MEERA_FOLDER}/${name}.webp`);
  const small = files.find((f) => f.toLowerCase() === `${MEERA_FOLDER}/${name}-512.webp`);
  inv += `| ${name} | ${png} | ${size ? `${size.width}x${size.height}` : '?'} | ${kb(fs.statSync(full).size)} | ${clear} | ${clear.startsWith('no') ? 'soft framed style' : 'cut-out if the corners are see-through, else soft framed style'} | ${big ? kb(fs.statSync(path.join(dir, big)).size) : 'missing'} / ${small ? kb(fs.statSync(path.join(dir, small)).size) : 'missing'} |\n`;
}
inv += missingMeera.length
  ? `\nMissing: ${missingMeera.map((n) => `\`${n}\``).join(', ')}.\n`
  : `\nAll ${meeraNames.length} expected Meera files were found (the 16 poses and the default \`meera.png\`); none is missing.\n`;
inv += `\n## Every image file in public/photos\n\n| File | Size | Orientation | Weight | Slot and pages |\n|---|---|---|---|---|\n`;
for (const f of images) {
  const size = imageSize(path.join(dir, f));
  const base = f.replace(/\.[a-z]+$/i, '').replace(/^meera\//, '');
  const slot = base.replace(/-(960|512)$/, '');
  const use = f.startsWith(`${MEERA_FOLDER}/`)
    ? slot === MEERA_DEFAULT
      ? 'Meera default picture (every pose without its own file)'
      : `Meera tour picture (${slot})`
    : /-(960|512)$/.test(base)
      ? `Small-screen copy of ${slot}`
      : (USED[slot] ?? 'Not used by any slot');
  inv += `| ${f} | ${size ? `${size.width}x${size.height}` : '?'} | ${size ? orientation(size.width, size.height) : '?'} | ${kb(fs.statSync(path.join(dir, f)).size)} | ${use} |\n`;
}
fs.writeFileSync(path.join(docs, 'IMAGE_INVENTORY.md'), inv);

const needed = Object.keys(PHOTO_SLOTS).filter((s) => !pickPhoto(s, files));
