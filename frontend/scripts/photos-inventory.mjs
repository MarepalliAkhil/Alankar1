slots += `## Which picture each page uses\n\n| Page | Full-window background | Framed header |\n|---|---|---|\n`;
slots += `| Home (/) | scrolling: Alankar reception, Salon, Spa, Parlor (one per section, crossfade) | none |\n| /salon | salon-background | salon-hero (a different picture) |\n| /spa | spa-background | spa-hero |\n| /beauty-parlor | parlor-background | parlor-hero |\n| Booking (/customer/book) | the division being booked (salon, spa, parlor), crossfading with the theme tint; "All" = shop-background | that division's hero (a different picture), or a close crop of shop-background for All |\n| Every other page: customer dashboard, bookings list, Zen Chat, wallet, packages, memberships, gift cards, shop, orders, invoices, profile; all receptionist, stylist and admin pages; login, register; For Zenotians | shop-background (Alankar reception) | none |\n\nEvery background sits under a soft veil (about 82 to 86 percent of the page colour, checked for AA against the real photos), is blurred about 10 px (about 14 px on staff pages) and is decorative (empty alt).\n\n`;
slots += `## STILL NEEDED\n\n`;
const missing = needed.filter((s) => !isTransparentSlot(s));
slots += missing.length
  ? `Missing photos (exact file names): ${missing.map((s) => `\`${s}.webp\` (or .jpg/.jpeg/.png)`).join(', ')}. Until added, the slot shows a plain themed gradient.\n\n`
  : `All seven photos are present: none of the Alankar, Salon, Spa and Parlor backgrounds or the three heroes is missing.\n\n`;
const meeraMissing = MEERA_POSES.filter((pose) => !pickPhoto(`meera-${pose}`, files));
const meeraDefault = pickPhoto(MEERA_DEFAULT, files);
slots += meeraDefault
  ? `Meera: the default picture \`${meeraDefault}\` is shown in every tour pose that has no file of its own (${meeraMissing.length} of ${MEERA_POSES.length} poses today). Add a \`meera-<pose>\` file and it is used automatically, with no code change.\n\n`
  : `Meera pictures (below) are not present: the tour shows a glass circle with the letter "M" in each pose's place. Add \`meera.png\` (the default) or a \`meera-<pose>\` file.\n\n`;
slots += `## Meera, the tour guide (3D character pictures, owner supplied)\n\nPNG, JPG, JPEG or WebP, **820x1024** (4:5 portrait, about 1024 px tall), in \`frontend/public/photos/meera/\` as \`meera-<pose>.<ext>\`. Best: a cut-out on a transparent background (PNG or WebP). A picture with a plain background also works: it is shown as a rounded image with a soft theme-tinted frame and faded edges. \`npm run photos:optimize\` turns each into WebP (keeping transparency). The admin has no photo-upload screen yet (only image URLs), so Meera pictures are files in that folder.\n\n| Slot | Size | Pose | Tour chapter | Status |\n|---|---|---|---|---|\n`;
const chapter = {
  wave: 'Welcome when the tour is restarted from the menu',
  point: 'Generic look-here tip',
  phone: 'Booking page tip',
  approve: 'A confirmed booking',
  chat: '4 Private chat; Zen Chat tip',
  wallet: '5 Pay and save',
  stars: '6 Visit and rate',
  shield: '7 Stay safe; Trusted devices tip',
  celebrate: 'Finale',
  namaste: '1 Welcome (first run; a restart uses wave)',
  scissors: '2 Pick a service',
  calendar: 'My bookings tip',
  waiting: '3 Waiting for the nod; a pending request',
  sorry: 'A declined request; a changed slot',
  gift: 'Gift cards tip',
  package: 'Packages and memberships tip',
};
for (const pose of MEERA_POSES) {
  const s = `meera-${pose}`;
  slots += `| ${s} | ${PHOTO_SLOTS[s].width}x${PHOTO_SLOTS[s].height} | ${SLOT_SHOWS[s]} | ${chapter[pose]} | ${pickPhoto(s, files) ? 'present' : meeraDefault ? 'STILL NEEDED (default meera picture shown)' : 'STILL NEEDED'} |\n`;
}
slots += `\nAlt text per pose, e.g. "Meera, your stylist guide, waving". The stage in the tour card is flexible (width clamp(120px, 32%, 200px), 4:5), so the same picture and the "M" circle scale with the card. A pose without its own file shows \`meera\`; the "M" circle shows only if \`meera\` is missing too.\n\n## All slots\n\n| Slot | Size | Photo today | What it shows |\n|---|---|---|---|\n`;
for (const [s, w] of Object.entries(PHOTO_SLOTS)) {
  slots += `| ${s} | ${w.width}x${w.height} | ${pickPhoto(s, files) ?? 'none (gradient)'} | ${SLOT_SHOWS[s]} |\n`;
}
fs.writeFileSync(path.join(docs, 'IMAGE_SLOTS.md'), slots);
console.log(
  `Wrote docs/IMAGE_INVENTORY.md (${images.length} files) and docs/IMAGE_SLOTS.md (${needed.length} slots without a photo).`,
);
